#!/usr/bin/env node
// Writes tokens/{light,dark}.json into the prototype's :root blocks and the clients in apps/, then checks WCAG contrast.
// Usage: node tools/tokens.mjs [prototype.html]
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const read = name => JSON.parse(readFileSync(new URL(`tokens/${name}.json`, root))).color;
const flat = group => Object.fromEntries(Object.entries(group).filter(([k]) => !k.startsWith('$')).map(([k, v]) => [k, v.$value]));
const light = flat(read('light')), dark = flat(read('dark'));

const page = new URL(process.argv[2] ?? 'index.html', root);
let html = readFileSync(page, 'utf8');
for (const [mode, values] of [['light', light], ['dark', dark]]) {
  const css = Object.entries(values).map(([k, v]) => `--${k}:${v};`).join(' ');
  const block = new RegExp(`/\\* tokens:${mode} \\*/[\\s\\S]*?/\\* /tokens \\*/`);
  if (!block.test(html)) throw new Error(`missing tokens:${mode} block`);
  html = html.replace(block, `/* tokens:${mode} */\n  ${css}\n  /* /tokens */`);
}
writeFileSync(page, html);

// Web uses every token. Its theme switch is data-theme, the same as the prototype.
const cssVars = values => Object.entries(values).map(([k, v]) => `--${k}:${v};`).join(' ');
writeFileSync(new URL('apps/web/src/styles/tokens.css', root), `/* Generated by tools/tokens.mjs from tokens/*.json. Do not edit. */
:root{color-scheme:light; ${cssVars(light)}}
:root[data-theme=dark]{color-scheme:dark; ${cssVars(dark)}}
`);

// iOS takes system backgrounds, labels and separators (docs/07-platforms.md#颜色), so only the role colors become assets.
const ASSET_COLORS = { AccentColor: 'jade', JadeWave: 'jade-wave', JadeSoft: 'jade-soft', OnJade: 'on-jade', Cinnabar: 'cinnabar', CinnabarSoft: 'cinnabar-soft', Amber: 'amber', AmberSoft: 'amber-soft', YouWave: 'you-wave', Overlap: 'overlap', UserBubble: 'user-bubble' };
const srgb = hex => {
  const [red, green, blue] = [1, 3, 5].map(i => `0x${hex.slice(i, i + 2)}`);
  return { color: { 'color-space': 'srgb', components: { alpha: hex.length > 7 ? (parseInt(hex.slice(7, 9), 16) / 255).toFixed(3) : '1.000', blue, green, red } }, idiom: 'universal' };
};
const assets = new URL('apps/ios/MiniCPM/Assets.xcassets/', root);
for (const [name, token] of Object.entries(ASSET_COLORS)) {
  const dir = new URL(`${name}.colorset/`, assets);
  mkdirSync(dir, { recursive: true });
  writeFileSync(new URL('Contents.json', dir), `${JSON.stringify({
    colors: [srgb(light[token]), { appearances: [{ appearance: 'luminosity', value: 'dark' }], ...srgb(dark[token]) }],
    info: { author: 'xcode', version: 1 },
  }, null, 2)}\n`);
}

const lum = hex => {
  const [r, g, b] = [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16) / 255).map(v => (v <= .03928 ? v / 12.92 : ((v + .055) / 1.055) ** 2.4));
  return .2126 * r + .7152 * g + .0722 * b;
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + .05) / (y + .05); };
const TEXT = 4.5, GRAPHIC = 3;
const PAIRS = [
  ['ink', 'surface', TEXT], ['ink-2', 'surface', TEXT], ['ink-3', 'surface', TEXT], ['ink-3', 'chrome', TEXT], ['ink-3', 'raised', TEXT], ['ink-3', 'sunken', TEXT],
  ['ink', 'user-bubble', TEXT], ['ink-2', 'amber-soft', TEXT], ['ink-2', 'cinnabar-soft', TEXT], ['ink-2', 'jade-soft', TEXT],
  ['jade', 'surface', TEXT], ['jade', 'jade-soft', TEXT], ['on-jade', 'jade', TEXT], ['cinnabar', 'surface', TEXT], ['cinnabar', 'cinnabar-soft', TEXT], ['on-cinnabar', 'cinnabar', TEXT], ['amber', 'amber-soft', TEXT],
  ['jade-wave', 'surface', GRAPHIC], ['you-wave', 'surface', GRAPHIC], ['amber', 'surface', GRAPHIC], ['control', 'surface', GRAPHIC], ['control', 'raised', GRAPHIC],
];
let failed = 0;
for (const [mode, t] of [['light', light], ['dark', dark]]) {
  for (const [fg, bg, min] of PAIRS) {
    const r = ratio(t[fg], t[bg]);
    if (r < min) { failed++; console.log(`FAIL ${mode} ${fg} on ${bg}: ${r.toFixed(2)} < ${min}`); }
  }
}
console.log(`${page.pathname.split('/').pop()} synced, ${PAIRS.length * 2 - failed}/${PAIRS.length * 2} contrast pairs pass`);
process.exitCode = failed ? 1 : 0;
